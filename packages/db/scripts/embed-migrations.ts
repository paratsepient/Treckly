/**
 * У браузері немає файлової системи, тому SQL-міграції Drizzle вбудовуються в
 * `src/migrations.generated.ts`. `--check` перевіряє, що вбудоване збігається з папкою migrations/.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const journal = JSON.parse(readFileSync(join(root, "migrations", "meta", "_journal.json"), "utf8")) as {
  entries: { tag: string }[];
};

const migrations = journal.entries.map(({ tag }) => ({
  tag,
  statements: readFileSync(join(root, "migrations", `${tag}.sql`), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter((s) => s !== ""),
}));

const output = `/* AUTO-GENERATED by scripts/embed-migrations.ts. Не редагувати вручну: запустіть \`pnpm --filter @dsp/db embed\`. */
export const MIGRATIONS: readonly { readonly tag: string; readonly statements: readonly string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;

const target = join(root, "src", "migrations.generated.ts");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // файла ще немає
  }
  if (current !== output) {
    console.error("migrations.generated.ts застарів: запустіть `pnpm --filter @dsp/db embed`.");
    process.exit(1);
  }
  console.log("PASS: вбудовані міграції актуальні.");
} else {
  writeFileSync(target, output);
  console.log(`Вбудовано міграцій: ${migrations.length}`);
}
