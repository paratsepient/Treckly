/**
 * Шестерня з 8 зубцями: ламана між внутрішнім (7.2) і зовнішнім (9.5) радіусами.
 * Зубець вужчий за западину, щоб на 16 px зубці читались окремо.
 */
const gear = ((): string => {
  const points: [number, number][] = [];
  const at = (radius: number, degrees: number): [number, number] => {
    const radians = (degrees * Math.PI) / 180;
    return [12 + radius * Math.cos(radians), 12 + radius * Math.sin(radians)];
  };
  for (let tooth = 0; tooth < 8; tooth += 1) {
    const centre = tooth * 45;
    points.push(at(7.2, centre - 15), at(9.5, centre - 8), at(9.5, centre + 8), at(7.2, centre + 15));
  }
  return `${poly(...points)}z`;
})();

