const HEADER =
  "AUTO-GENERATED by packages/design-tokens/scripts/generate.ts. Не редагувати вручну: змінюйте src/ і запускайте `pnpm --filter @index/design-tokens generate`.";

const v = cssVariableName;

function colorReferenceCss({ ref, alpha, tint }: ColorReference): string {
  const base = `var(${v("color", ref)})`;
  if (tint !== undefined && alpha !== undefined) {
    throw new Error(`Токен з ${ref}: tint і alpha разом не підтримуються.`);
  }
  if (tint !== undefined) {
    // Непрозора домішка: валідатор рахує той самий колір через composite(tint, amount, base).
    return `color-mix(in srgb, var(${v("color", tint.ref)}) ${round(tint.amount * 100)}%, ${base})`;
  }
  if (alpha === undefined) {
    return base;
  }
  // color-mix із transparent дає рівно той самий колір з alpha, не дублюючи HEX.
  return `color-mix(in srgb, ${base} ${round(alpha * 100)}%, transparent)`;
}

function shadowCss(layers: readonly ShadowLayer[]): string {
  if (layers.length === 0) {
    return "none";
  }
  return layers
    .map(
      (layer) =>
        `${layer.inset ? "inset " : ""}${layer.x ? `${layer.x}px` : "0"} ${layer.y}px ${layer.blur}px ${layer.spread}px ${colorReferenceCss({
          ref: layer.color,
          alpha: layer.alpha,
        })}`,
    )
    .join(", ");
}

function round(value: number, digits = 4): number {
  const factor = 10 ** digits;
  return Math.round(value * factor) / factor;
}

function themeBlock(theme: ThemeName, indent: string, palette: PaletteName = activePalette): string[] {
  const mapping = palettes[palette][theme];
  const shadowSet = paletteShadows[palette][theme];
  return [
    `${indent}color-scheme: ${theme};`,
    ...semanticColorNames.map(
      (name) => `${indent}${v(null, name)}: ${colorReferenceCss(mapping[name])};`,
    ),
    // Гніздо додається через кому до тіні кнопки, тож порожнє — прозорий шар, а не none.
    ...shadowNames.map(
      (name) =>
        `${indent}${v("shadow", name)}: ${name === "socket" && shadowSet[name].length === 0 ? "0 0 0 0 transparent" : shadowCss(shadowSet[name])};`,
    ),
    ...focusShadowLines(palette, indent),
    // Тональні переходи: колір верхнього краю → прозорий; накладаються як background-image.
    ...tonalEffectNames.map((name) => {
      const effect = paletteTonal[palette][theme][name];
      return `${indent}${v("tonal", name)}: ${effect ? `linear-gradient(180deg, ${colorReferenceCss(effect)}, transparent)` : "none"};`;
    }),
    // Злита вкладка навігації: радіальні світло й тінь від лівого краю, що згасають до стику з панеллю.
    (() => {
      const tab = paletteTabTonal[palette][theme];
      return `${indent}${v("tonal", "tab")}: ${
        tab
          ? `radial-gradient(130% 100% at 0 0, ${colorReferenceCss(tab.light)}, transparent 70%), radial-gradient(130% 100% at 0 100%, ${colorReferenceCss(tab.shade)}, transparent 70%)`
          : "none"
      };`;
    })(),
    // Блиск: еліпс у центрі зображення шириною в 3 кнопки; компонент ставить його на верхню кромку й зсуває.
    (() => {
      const sheen = paletteSheen[palette][theme];
      return `${indent}${v(null, "sheen")}: ${sheen ? `radial-gradient(ellipse 12% 50% at 50% 50%, ${colorReferenceCss(sheen)}, transparent)` : "none"};`;
    })(),
    // Слабка смуга через усю висоту: вузька діагональ у центрі зображення тієї ж ширини.
    (() => {
      const band = paletteSheenBand[palette][theme];
      return `${indent}${v(null, "sheen-band")}: ${band ? `linear-gradient(110deg, transparent 40%, ${colorReferenceCss(band)} 50%, transparent 60%)` : "none"};`;
    })(),
    // Аліаси оголошуються в кожному блоці теми: var() розв'язується там, де оголошено,
    // і аліас лише в :root «заморозив» би значення світлої теми для вкладених [data-theme].
    ...Object.entries(deprecatedShadowAliases).map(
      ([alias, target]) => `${indent}${v("shadow", alias)}: var(${v("shadow", target)});`,
    ),
  ];
}

/**
 * Індикатор фокуса як box-shadow: зовнішній і внутрішній (для контейнерів з overflow).
 * Посилається на var(--ix-focus-glow), тому оголошується в кожному блоці теми.
 */
function focusShadowLines(palette: PaletteName, indent: string): string[] {
  const width = `var(${v("focus", "width")})`;
  const color = `var(${v(null, "focus-glow")})`;
  const glow = paletteFocusStyle[palette] === "glow";
  // v1.2 — лише світіння (без лінії); до v1.2 — суцільне кільце.
  const outer = glow ? `0 0 ${focusGlow.blur}px ${focusGlow.spread}px ${color}` : `0 0 0 ${width} ${color}`;
  const inner = glow
    ? `inset 0 0 ${focusGlow.insetBlur}px ${focusGlow.insetSpread}px ${color}`
    : `inset 0 0 0 ${width} ${color}`;
  return [
    `${indent}${v("focus", "shadow")}: ${outer};`,
    `${indent}${v("focus", "shadow-inset")}: ${inner};`,
    // Пульсація фокуса (стиль glow): постійна частина (steady) — перевірене світіння
    // focus-shadow, тож індикатор ніколи не зникає (WCAG 2.4.7); пульсує лише ширший ореол
    // поверх нього (рішення власника 05.11.2026, замість повного згасання).
    // Без glow пульсації немає, а steady — те саме кільце, що й focus-shadow.
    `${indent}${v("focus", "pulse-shadow")}: ${glow ? `0 0 ${focusGlow.pulseBlur}px ${focusGlow.pulseSpread}px ${color}` : "none"};`,
    `${indent}${v("focus", "pulse-shadow-inset")}: ${glow ? `inset 0 0 ${focusGlow.pulseBlur}px ${focusGlow.pulseSpread}px ${color}` : "none"};`,
    // Колір світіння для шарів, що малюють його не box-shadow (контур «папки» вкладок у SVG).
    // Без glow — прозорий: фокус там показує кільце.
    `${indent}${v("focus", "pulse-color")}: ${glow ? color : "transparent"};`,
    `${indent}${v("focus", "steady-shadow")}: ${outer};`,
    `${indent}${v("focus", "steady-shadow-inset")}: ${inner};`,
    // Межа заглиблених контролів: у v1.2 прозора (форму дає тінь лунки), раніше — контур.
    ...(paletteWellBorder[palette] === "shadow"
      ? [
          `${indent}${v("well", "border")}: transparent;`,
          `${indent}${v("well", "border-hover")}: transparent;`,
          `${indent}${v("well", "error-ring")}: inset 0 0 0 1px var(${v(null, "error")});`,
          `${indent}${v("control", "border-width")}: 0px;`,
          `${indent}${v("raised", "border")}: transparent;`,
        ]
      : [
          `${indent}${v("well", "border")}: var(${v(null, "border-strong")});`,
          `${indent}${v("well", "border-hover")}: var(${v(null, "foreground-muted")});`,
          // Межу помилки тут дає сама рамка.
          `${indent}${v("well", "error-ring")}: 0 0 0 0 transparent;`,
          `${indent}${v("control", "border-width")}: 1px;`,
          `${indent}${v("raised", "border")}: var(${v(null, "border-strong")});`,
        ]),
  ];
}

/**
 * Палітра для порівняння Before/After (generated/comparison/). Підключається лише
 * інструментами Playground і діє всередині [data-palette]; основний tokens.css її не містить.
 * Селектори специфічніші за основні блоки тем, тому файл може йти після tokens.css.
 */
export function renderPaletteCss(palette: PaletteName): string {
  const scope = `[data-palette="${palette}"]`;
  // Форма версії: радіуси незалежні від теми, тому оголошуються один раз на корені області.
  const shape = (Object.keys(radii) as RadiusName[])
    .filter((name) => paletteRadii[palette][name] !== radii[name].value)
    .map((name) => `  ${v("radius", name)}: ${paletteRadii[palette][name]}px;`);
  return [
    `/* ${HEADER} */`,
    `/* Палітра «${palette}» лише для порівняння. Не підключати в продукті. */`,
    "",
    ...(shape.length > 0 ? [`:root${scope},\n${scope} {`, ...shape, "}", ""] : []),
    `:root${scope},\n${scope}[data-theme="light"],\n${scope} [data-theme="light"] {`,
    ...themeBlock("light", "  ", palette),
    "}",
    "",
    `${scope}[data-theme="dark"],\n${scope} [data-theme="dark"] {`,
    ...themeBlock("dark", "  ", palette),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    `  :root${scope}:not([data-theme="light"]) {`,
    ...themeBlock("dark", "    ", palette),
    "  }",
    "}",
    "",
  ].join("\n");
}

export function renderCss(): string {
  const root: string[] = ["  /* Primitive colors: однакові для всіх тем. */"];
  for (const [name, hex] of Object.entries(primitiveColors)) {
    root.push(`  ${v("color", name)}: ${hex};`);
  }

  root.push("", "  /* Typography */");
  for (const [name, value] of Object.entries(fontFamilies)) {
    root.push(`  ${v("font", `family-${name}`)}: ${value};`);
  }
  for (const [name, value] of Object.entries(fontWeights)) {
    root.push(`  ${v("font", `weight-${name}`)}: ${value};`);
  }
  for (const [name, style] of Object.entries(textStyles)) {
    const family = `var(${v("font", `family-${style.family}`)})`;
    const weight = fontWeights[style.weight];
    root.push(
      `  ${v("font", `${name}-size`)}: ${style.size}px;`,
      `  ${v("font", `${name}-line-height`)}: ${style.lineHeight}px;`,
      `  ${v("font", `${name}-weight`)}: ${weight};`,
      `  ${v("font", `${name}-letter-spacing`)}: ${style.letterSpacing}em;`,
      `  ${v("font", name)}: ${weight} ${style.size}px/${style.lineHeight}px ${family};`,
    );
  }

  root.push("", "  /* Spacing: крок 4 px */");
  for (const [name, value] of Object.entries(spacing)) {
    root.push(`  ${v("space", name)}: ${value}px;`);
  }

  root.push("", "  /* Radius */");
  for (const [name, token] of Object.entries(radii)) {
    root.push(`  ${v("radius", name)}: ${token.value}px;`);
  }

  root.push("", "  /* Layout: ширини каркаса (чернетка PageShell & Layout) */");
  for (const [name, value] of Object.entries(layoutSizes)) {
    root.push(`  ${v("layout", name)}: ${value}px;`);
  }

  root.push("", "  /* Motion */");
  for (const [name, value] of Object.entries(durations)) {
    root.push(`  ${v("duration", name)}: ${value}ms;`);
  }
  for (const [name, value] of Object.entries(easings)) {
    root.push(`  ${v("easing", name)}: ${value};`);
  }

  root.push(
    "",
    "  /* Focus */",
    `  ${v("focus", "width")}: ${focusRing.width}px;`,
    `  ${v("focus", "offset")}: ${focusRing.offset}px;`,
    `  ${v("focus", "inset-offset")}: ${focusRing.insetOffset}px;`,
    // Період циклічного руху, а не тривалість переходу: тому поза шкалою durations.
    `  ${v("focus", "pulse-duration")}: ${focusGlow.pulseDuration}ms;`,
    // Розміри світіння окремо від box-shadow — для шарів, що малюють його інакше
    // (SVG-контур «папки» вкладок): смуга й ореол пульсації, px.
    `  ${v("focus", "glow-spread")}: ${focusGlow.spread}px;`,
    `  ${v("focus", "glow-blur")}: ${focusGlow.blur}px;`,
    `  ${v("focus", "pulse-spread")}: ${focusGlow.pulseSpread}px;`,
    `  ${v("focus", "pulse-blur")}: ${focusGlow.pulseBlur}px;`,
    `  ${v(null, "sheen-duration")}: ${sheenDuration}ms;`,
    `  ${v(null, "sheen-height")}: ${sheenHeight}px;`,
  );

  const reducedMotion = Object.keys(durations).map(
    (name) => `    ${v("duration", name)}: 0ms;`,
  );

  return [
    `/* ${HEADER} */`,
    "",
    "/* Локальний Inter; @import має стояти до будь-яких правил. */",
    '@import "./fonts.css";',
    "",
    ":root {",
    ...root,
    "}",
    "",
    "/* Light — тема за замовчуванням. */",
    ':root,\n[data-theme="light"] {',
    ...themeBlock("light", "  "),
    "}",
    "",
    '[data-theme="dark"] {',
    ...themeBlock("dark", "  "),
    "}",
    "",
    "/* Системна темна тема, якщо застосунок явно не вибрав light. */",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    ...themeBlock("dark", "    "),
    "  }",
    "}",
    "",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    ...reducedMotion,
    "  }",
    "}",
    "",
  ].join("\n");
}

/**
 * @font-face для локального Inter. Шлях відносний до generated/, тому працює
 * і з бандлером, і при прямому підключенні файлу.
 */
export function renderFontsCss(): string {
  const faces = interSubsets.map((subset) =>
    [
      `/* ${subset.subset} */`,
      "@font-face {",
      `  font-family: "${fontFaceFamily}";`,
      "  font-style: normal;",
      `  font-weight: ${interWeightRange};`,
      "  font-display: swap;",
      `  src: url("../fonts/inter/${subset.file}") format("woff2");`,
      `  unicode-range: ${subset.unicodeRange};`,
      "}",
    ].join("\n"),
  );
  return [
    `/* ${HEADER} */`,
    "/* Inter © The Inter Project Authors. SIL Open Font License 1.1 — fonts/inter/OFL.txt. */",
    "",
    faces.join("\n\n"),
    "",
  ].join("\n");
}

function resolvedValue({ ref, alpha, tint }: ColorReference): string {
  const hex = tint
    ? toHex(composite(parseHex(primitiveColors[tint.ref]), tint.amount, parseHex(primitiveColors[ref])))
    : primitiveColors[ref];
  if (alpha === undefined) {
    return hex;
  }
  const r = Number.parseInt(hex.slice(1, 3), 16);
  const g = Number.parseInt(hex.slice(3, 5), 16);
  const b = Number.parseInt(hex.slice(5, 7), 16);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

/** Машинозчитуваний реєстр: те саме джерело, що й CSS, у розгорнутому вигляді для preview та інструментів. */
function semanticJson(palette: PaletteName) {
  return Object.fromEntries(
    themeNames.map((theme) => [
      theme,
      Object.fromEntries(
        semanticColorNames.map((name) => {
          const reference = palettes[palette][theme][name];
          return [
            name,
            {
              ref: reference.ref,
              ...(reference.alpha === undefined ? {} : { alpha: reference.alpha }),
              ...(reference.tint === undefined ? {} : { tint: reference.tint }),
              value: resolvedValue(reference),
              cssVariable: v(null, name),
            },
          ];
        }),
      ),
    ]),
  );
}

export function renderJson(): string {
  const semantic = semanticJson(activePalette);

  const data = {
    $comment: HEADER,
    primitives: {
      steps: colorSteps,
      colors: primitiveColors,
    },
    palette: activePalette,
    semantic,
    /** Усі палітри (активна й контрольні точки) — для порівняння в інструментах. */
    palettes: Object.fromEntries(paletteNames.map((palette) => [palette, semanticJson(palette)])),
    typography: { families: fontFamilies, weights: fontWeights, styles: textStyles },
    spacing,
    radius: radii,
    elevation: {
      levels: elevationLevels,
      shadows: Object.fromEntries(
        paletteNames.map((palette) => [
          palette,
          Object.fromEntries(
            themeNames.map((theme) => [
              theme,
              Object.fromEntries(shadowNames.map((name) => [name, shadowCss(paletteShadows[palette][theme][name])])),
            ]),
          ),
        ]),
      ),
      deprecatedAliases: deprecatedShadowAliases,
    },
    layout: { sizes: layoutSizes, breakpoints: layoutBreakpoints },
    motion: { durations, easings },
    focus: focusRing,
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}

/** Усі палітри × теми: активна палітра й контрольні точки перевіряються однаково. */
export function evaluateAll(): ContrastResult[] {
  return paletteNames.flatMap((palette) => themeNames.flatMap((theme) => evaluateTheme(theme, palette)));
}

function summarize(results: readonly ContrastResult[]) {
  return {
    total: results.length,
    pass: results.filter((result) => result.status === "pass").length,
    fail: results.filter((result) => result.status === "fail").length,
    exempt: results.filter((result) => result.status === "exempt").length,
  };
}

export function renderContrastJson(results: readonly ContrastResult[]): string {
  const summary = Object.fromEntries(
    paletteNames.map((palette) => [
      palette,
      Object.fromEntries(
        themeNames.map((theme) => [
          theme,
          summarize(results.filter((result) => result.palette === palette && result.theme === theme)),
        ]),
      ),
    ]),
  );
  const data = {
    $comment: HEADER,
    standard: "WCAG 2.2 relative luminance / contrast ratio",
    activePalette,
    thresholds: requirementThresholds,
    checksPerTheme: contrastChecks.length,
    summary,
    results: results.map((result) => ({
      palette: result.palette,
      theme: result.theme,
      id: result.id,
      group: result.group,
      label: result.label,
      requirement: result.requirement,
      foreground: result.foreground,
      background: result.background,
      foregroundHex: result.foregroundHex,
      backgroundHex: result.backgroundHex,
      ratio: round(result.ratio),
      ratioText: formatRatio(result.ratio),
      threshold: result.threshold,
      status: result.status,
      ...(result.note === undefined ? {} : { note: result.note }),
      ...(result.compensatedBy === undefined ? {} : { compensatedBy: result.compensatedBy }),
      ...(result.minimum === undefined ? {} : { minimum: result.minimum }),
      ...(result.reason === undefined ? {} : { reason: result.reason }),
    })),
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}

const statusLabel = { pass: "PASS", fail: "FAIL", exempt: "EXEMPT" } as const;

export function renderContrastMarkdown(results: readonly ContrastResult[]): string {
  const lines = [
    `<!-- ${HEADER} -->`,
    "",
    "# Звіт контрастності WCAG 2.2",
    "",
    "Значення обчислено кодом (`src/contrast`). Ratio відкинуто до двох знаків, порівняння з порогом — без округлення.",
    "EXEMPT — пара не має порогу WCAG (disabled або декоративний сигнал); причину наведено в примітці.",
    "Декоративний виняток діє лише поки проходять його компенсувальні перевірки; disabled має внутрішній мінімум. Інакше статус — FAIL.",
  ];
  const noteCell = (result: ContrastResult): string =>
    [
      result.note,
      result.minimum === undefined ? undefined : `Мінімум: ${result.minimum}:1.`,
      result.compensatedBy === undefined
        ? undefined
        : `Компенсація: ${result.compensatedBy.map((id) => `\`${id}\``).join(", ")}.`,
      result.reason === undefined ? undefined : `**${result.reason}**`,
    ]
      .filter((part) => part !== undefined)
      .join(" ");
  const baselines = paletteNames.filter((palette) => palette !== activePalette);
  lines.push(
    "",
    `Активна палітра: **${activePalette}**. Контрольні точки для порівняння: ${baselines.map((name) => `**${name}**`).join(", ")}.`,
    "",
    "## Підсумок",
    "",
    "| Палітра | Тема | PASS | FAIL | EXEMPT | Усього |",
    "| --- | --- | ---: | ---: | ---: | ---: |",
    ...paletteNames.flatMap((palette) =>
      themeNames.map((theme) => {
        const own = summarize(results.filter((result) => result.palette === palette && result.theme === theme));
        return `| ${palette} | ${theme} | ${own.pass} | ${own.fail} | ${own.exempt} | ${own.total} |`;
      }),
    ),
  );
  for (const theme of themeNames) {
    const own = results.filter((result) => result.palette === activePalette && result.theme === theme);
    const before = (baseline: PaletteName, id: string): ContrastResult | undefined =>
      results.find((result) => result.palette === baseline && result.theme === theme && result.id === id);
    lines.push(
      "",
      `## ${theme === "light" ? "Light" : "Dark"} — ${activePalette}`,
      "",
      `| Група | Пара (foreground / background) | ${baselines.map((name) => `${name}`).join(" | ")} | FG | BG | Ratio | Поріг | Статус | Примітка |`,
      `| --- | --- | ${baselines.map(() => "---:").join(" | ")} | --- | --- | ---: | ---: | --- | --- |`,
      ...own.map((result) => {
        const previous = baselines.map((baseline) => {
          const item = before(baseline, result.id);
          return item ? `${formatRatio(item.ratio)} ${statusLabel[item.status]}` : "—";
        });
        return `| ${result.group} | ${result.label} | ${previous.join(" | ")} | \`${result.foregroundHex}\` | \`${result.backgroundHex}\` | ${formatRatio(result.ratio)} | ${result.threshold === null ? "—" : `${result.threshold}:1`} | ${statusLabel[result.status]} | ${noteCell(result)} |`;
      }),
    );
  }
  lines.push("");
  return lines.join("\n");
}

/** Повний набір generated-файлів: шлях відносно кореня пакета → вміст. */
export function renderAll(): Record<string, string> {
  const results = evaluateAll();
  const comparison = Object.fromEntries(
    paletteNames
      .filter((palette) => palette !== activePalette)
      .map((palette) => [`generated/comparison/palette-${palette}.css`, renderPaletteCss(palette)]),
  );
  return {
    ...comparison,
    "generated/tokens.css": renderCss(),
    "generated/fonts.css": renderFontsCss(),
    "generated/tokens.json": renderJson(),
    "generated/contrast-report.json": renderContrastJson(results),
    "generated/contrast-report.md": renderContrastMarkdown(results),
  };
}
