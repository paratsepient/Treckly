/**
 * v1.2: світіння без окремої лінії, що повільно пульсує.
 *
 * Світіння — одна тінь зі spread і невеликим розмиттям: біля краю елемента воно
 * майже повної інтенсивності й згасає назовні за кілька пікселів. Саме ця щільна
 * смуга є індикатором фокуса для WCAG 1.4.11, тому валідатор перевіряє колір
 * світіння з фактичною інтенсивністю смуги (`glowBandIntensity`), а не повний колір.
 * На контролях-хостах пульсації (кнопки, вкладки, сегменти, choice, select, навігація)
 * світіння разом із ширшим ореолом повністю згасає й розгоряється знову. Валідатор
 * перевіряє смугу на піку пульсу.
 *
 * Прийнятий ризик (рішення власника дизайну, 2026-11-03): у мінімумі циклу індикатора
 * фокуса на цих контролях немає зовсім, що суперечить WCAG 2.4.7 / 1.4.11 «фокус видно
 * завжди». При prefers-reduced-motion світіння постійне. Текстові поля, панелі й інші
 * елементи без пульсації мають постійне світіння.
 */
export const focusGlow = {
  /** Розширення й розмиття зовнішнього світіння, px. Загальна ширина ≈ spread + blur / 2. */
  spread: 2,
  blur: 1.5,
  /** Внутрішнє світіння для елементів у контейнерах з overflow. */
  insetSpread: 2,
  insetBlur: 1.5,
  /** Відстань від краю елемента, на якій вимірюється смуга індикатора (середина 2-px смуги). */
  bandDistance: 1,
  /**
   * Ореол пульсації на піку, px: ширший і м'якший за смугу світіння. На 40 % тонший за
   * перший варіант `0 0 6px 3px`; смуга біля краю (spread/blur вище) не змінюється —
   * на ній тримається контраст індикатора.
   */
  pulseSpread: 1.8,
  pulseBlur: 3.6,
  /** Повний цикл «розгоряння — згасання», мс. Повільний, щоб читався як дихання, а не блимання. */
  pulseDuration: 2800,
} as const;

/** Функція розподілу стандартного нормального розподілу (апроксимація erf, похибка < 1.5e-7). */
function normalCdf(x: number): number {
  const t = 1 / (1 + 0.3275911 * (Math.abs(x) / Math.SQRT2));
  const poly = t * (0.254829592 + t * (-0.284496736 + t * (1.421413741 + t * (-1.453152027 + t * 1.061405429))));
  const erf = 1 - poly * Math.exp(-((x * x) / 2));
  return x >= 0 ? 0.5 * (1 + erf) : 0.5 * (1 - erf);
}

/**
 * Інтенсивність box-shadow на відстані `distance` від краю елемента.
 * CSS-розмиття b — гаусів фільтр із σ = b / 2, застосований до форми, розширеної на spread.
 */
export function glowBandIntensity(spread: number, blur: number, distance: number): number {
  if (blur === 0) return distance < spread ? 1 : 0;
  return normalCdf((spread - distance) / (blur / 2));
}

